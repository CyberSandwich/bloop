// The page build (tools/build-pages.mjs, design.md section 6, Site build): its rules, the one source of every page's
// chrome, the head tags, the sitemap and robots.txt.
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import {
  buildAll,
  chromeFor,
  fill,
  headOfHand,
  injectChrome,
  loadDocs,
  renderDoc,
  site,
  splitFrontmatter,
  staleFiles,
  usDate,
} from "../../tools/build-pages.mjs";
import { NEVER_SAY } from "./never-say.ts";

const ROOT = fileURLToPath(new URL("../../", import.meta.url));
const read = (rel: string) => readFileSync(`${ROOT}${rel}`, "utf8");
const built = buildAll();
const docs = loadDocs();
const pathOf = (rel: string) =>
  rel
    .replace(/^public/, "")
    .replace(/\.html$/, "")
    .replace(/^\/index$/, "/");
const pages = [...built].filter(([rel]) => rel.endsWith(".html"));
const region = (html: string, name: string) =>
  new RegExp(`<!-- build:${name} -->\\n([\\s\\S]*?)\\n\\s*<!-- /build:${name} -->`).exec(html)?.[1] ?? "";
const hrefs = (html: string) => [...html.matchAll(/href="([^"]+)"/g)].map((m) => m[1] ?? "");

describe("the generated pages are what the build produces (the drift gate)", () => {
  it.each([...built.keys()])("%s on disk equals the build's output", (rel) => {
    expect(read(rel)).toBe(built.get(rel));
  });

  it("no generated page is left behind by a deleted content file", () => {
    expect(staleFiles(built)).toEqual([]);
  });

  it("every generated page says where its source is", () => {
    for (const doc of docs) {
      expect(built.get(doc.out)).toContain(
        `<!-- GENERATED by tools/build-pages.mjs from ${doc.file}. Edit that file, then run npm run build:pages. -->`,
      );
    }
  });

  it("the sitemap and robots.txt are generated, not hand-kept", () => {
    expect([...built.keys()]).toEqual(expect.arrayContaining(["public/sitemap.xml", "public/robots.txt"]));
  });
});

describe("one source for every page's chrome", () => {
  const owned = new Set(built.keys());
  const files = (readdirSync(`${ROOT}public`, { recursive: true }) as string[]).filter((f) => f.endsWith(".html"));

  it("every html page that draws a nav or a footer is owned by the build", () => {
    for (const f of files) {
      const html = read(`public/${f}`);
      if (/<header class="nav">|<footer class="footer">|build:(nav|footer)/.test(html)) {
        expect(owned.has(`public/${f}`), `public/${f} draws site chrome but the build does not own it`).toBe(true);
      }
    }
  });

  it.each(pages.map(([rel]) => rel))(
    "%s holds the nav, the footer and the head block, each between its markers",
    (rel) => {
      const html = read(rel);
      for (const name of ["seo", "nav", "footer"]) {
        expect(html.match(new RegExp(`<!-- build:${name} -->`, "g")), name).toHaveLength(1);
        expect(html.match(new RegExp(`<!-- /build:${name} -->`, "g")), name).toHaveLength(1);
      }
    },
  );

  it.each(pages.map(([rel]) => rel))(
    "%s lists the nav links and the footer links from content/site.json, in order",
    (rel) => {
      const html = read(rel);
      const want = (where: string) => site.links.filter((l) => l.in.includes(where)).map((l) => l.href);
      expect(hrefs(region(html, "nav")).filter((h) => !h.startsWith("https:") && h !== "/")).toEqual(want("nav"));
      expect(
        hrefs(region(html, "footer")).filter((h) => !h.startsWith("https:") && !h.startsWith("mailto:") && h !== "/"),
      ).toEqual(want("footer"));
    },
  );

  it("Terms is in the nav and the footer, so in the mobile menu and the desktop pill", () => {
    expect(site.links.find((l) => l.href === "/terms")?.in).toEqual(["nav", "footer"]);
  });

  it("a page whose chrome differs from the source is caught", () => {
    for (const p of site.pages) {
      const html = read(`public/${p.file}`);
      const blocks = chromeFor(headOfHand(p));
      expect(injectChrome(html, blocks, p.file)).toBe(html);
      const nav = html.replace('<a href="/privacy">Privacy</a>', '<a href="/privacy">Privacy Policy</a>');
      expect(nav).not.toBe(html);
      expect(injectChrome(nav, blocks, p.file)).not.toBe(nav);
      const footer = html.replace("© 2026 bloop", "© 2025 bloop");
      expect(injectChrome(footer, blocks, p.file)).not.toBe(footer);
    }
  });

  it("a region the page lacks, or a block the build lacks, is an error", () => {
    expect(() => injectChrome("<html></html>", { nav: "x" }, "x")).toThrow(/no build:nav region/);
    expect(() => injectChrome("  <!-- build:nope -->\n  <!-- /build:nope -->", {}, "x")).toThrow(/unknown region nope/);
  });

  it("the current page is marked in the nav and the footer; an article marks Articles", () => {
    expect(region(built.get("public/privacy.html") ?? "", "nav")).toContain('<a href="/privacy" aria-current="page">');
    expect(region(built.get("public/privacy.html") ?? "", "footer")).toContain(
      '<a href="/privacy" aria-current="page">',
    );
    for (const rel of ["public/articles.html", "public/articles/how-bloop-works.html"]) {
      expect(region(built.get(rel) ?? "", "nav")).toContain('<a href="/articles" aria-current="page">');
    }
    expect(region(built.get("public/index.html") ?? "", "nav")).not.toContain("aria-current");
  });

  it("every Waitlist link names its page as its source", () => {
    expect(built.get("public/privacy.html")).toContain("https://tally.so/r/Yj4KAN?source=privacy");
    expect(built.get("public/articles/how-bloop-works.html")).toContain("https://tally.so/r/Yj4KAN?source=articles");
    expect(built.get("public/404.html")).toContain("https://tally.so/r/Yj4KAN?source=404");
  });
});

describe("the head of every page", () => {
  const indexable = pages.filter(([rel]) => rel !== "public/404.html");
  const ld = (html: string) =>
    [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)].map((m) => JSON.parse(m[1] ?? ""));

  it.each(indexable.map(([rel]) => rel))(
    "%s has a title, description, canonical, Open Graph and Twitter tags",
    (rel) => {
      const html = built.get(rel) ?? "";
      const url = `${site.origin}${pathOf(rel)}`;
      expect(html).toContain(`<link rel="canonical" href="${url}">`);
      expect(html).toContain(`<meta property="og:url" content="${url}">`);
      expect(html).toContain(`<meta property="og:image" content="${site.origin}/og.png">`);
      expect(html).toContain(`<meta name="twitter:image" content="${site.origin}/og.png">`);
      expect(html).toContain('<meta name="twitter:card" content="summary_large_image">');
      const title = /<title>([^<]+)<\/title>/.exec(html)?.[1] ?? "";
      expect(title).toMatch(/^bloop: /);
      expect(html).toContain(`<meta property="og:title" content="${title}">`);
      expect(html).toContain(`<meta name="twitter:title" content="${title}">`);
      const description = /<meta name="description" content="([^"]+)">/.exec(html)?.[1] ?? "";
      expect(description.length).toBeGreaterThan(30);
      expect(description.length).toBeLessThanOrEqual(170);
      expect(html).toContain(`<meta property="og:description" content="${description}">`);
      expect(html).not.toContain('name="robots"');
    },
  );

  it("the 404 page is noindex, with no canonical, previews or structured data", () => {
    const html = built.get("public/404.html") ?? "";
    expect(html).toContain('<meta name="robots" content="noindex">');
    expect(html).not.toMatch(/canonical|og:|twitter:|ld\+json/);
  });

  it("the landing page carries an Organization and a WebSite", () => {
    const [graph] = ld(built.get("public/index.html") ?? "");
    const types = graph["@graph"].map((n: { "@type": string }) => n["@type"]);
    expect(types).toEqual(["Organization", "WebSite"]);
    expect(graph["@graph"][1].publisher).toEqual({ "@id": graph["@graph"][0]["@id"] });
  });

  it("an article carries an Article with its own dates and a reading time that its words support", () => {
    for (const doc of docs.filter((d) => d.meta.kind === "article")) {
      const html = built.get(doc.out) ?? "";
      const [node] = ld(html);
      expect(node["@type"]).toBe("Article");
      expect(node.datePublished).toBe(doc.meta.published);
      expect(node.dateModified).toBe(doc.meta.updated ?? doc.meta.published);
      expect(node.url).toBe(`${site.origin}${doc.path}`);
      expect(html).toContain(`<meta property="article:published_time" content="${doc.meta.published}">`);
      const minutes = Number(/(\d+) min read<\/p>/.exec(html)?.[1]);
      const text = (html.split('<div class="legal-text">')[1] ?? "").replace(/<[^>]+>/g, " ");
      const words = text.split(/\s+/).filter(Boolean).length;
      expect(Math.abs(minutes - words / 220), `${doc.slug}: ${minutes} min for ${words} words`).toBeLessThanOrEqual(1);
      expect(minutes).toBeGreaterThanOrEqual(1);
    }
  });

  it("a legal page carries a WebPage dated by its effective day, and the index a CollectionPage", () => {
    for (const doc of docs.filter((d) => d.meta.kind === "legal")) {
      const [node] = ld(built.get(doc.out) ?? "");
      expect(node["@type"]).toBe("WebPage");
      expect(node.dateModified).toBe(doc.meta.effective);
    }
    expect(ld(built.get("public/articles.html") ?? "")[0]["@type"]).toBe("CollectionPage");
  });

  it("structured data never closes its script tag early", () => {
    for (const [, html] of pages)
      for (const m of html.matchAll(/ld\+json">([\s\S]*?)<\/script>/g)) expect(m[1]).not.toContain("<");
  });
});

describe("sitemap.xml and robots.txt", () => {
  const sitemap = built.get("public/sitemap.xml") ?? "";
  const robots = built.get("public/robots.txt") ?? "";
  const locs = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]);

  it("lists the landing page and every content page, once, with the date its content gives", () => {
    expect(locs).toEqual(["/", ...docs.map((d) => d.path)].map((p) => `${site.origin}${p}`));
    for (const d of docs.filter((x) => x.meta.kind !== "index")) {
      const date = d.meta.updated ?? d.meta.published ?? d.meta.effective;
      expect(sitemap).toContain(`<url><loc>${site.origin}${d.path}</loc><lastmod>${date}</lastmod></url>`);
    }
  });

  it("leaves out the 404 page, the app pages and the demo redirect", () => {
    for (const p of ["/404", "/s", "/a", "/code", "/demo", "/g", "/me"])
      expect(locs).not.toContain(`${site.origin}${p}`);
  });

  it("robots.txt allows the site, keeps crawlers off the API and names the sitemap", () => {
    expect(robots).toBe(`User-agent: *\nAllow: /\nDisallow: /api/\n\nSitemap: ${site.origin}/sitemap.xml\n`);
    for (const l of locs) expect(new URL(l ?? "").pathname.startsWith("/api/")).toBe(false);
  });

  it("llms.txt is generated: the name, the landing's line, what bloop is, and every content page once with its description", () => {
    const llms = built.get("public/llms.txt") ?? "";
    expect(read("public/llms.txt")).toBe(llms);
    const landing = site.pages.find((p) => p.path === "/");
    expect(llms.startsWith(`# ${site.name}\n\n> ${landing?.description}\n\n${site.about}\n\n## Articles\n`)).toBe(true);
    const links = [...llms.matchAll(/^- \[([^\]]+)\]\(([^)]+)\): (.+)$/gm)];
    expect(links.map((m) => m[2])).toEqual(
      [...docs.filter((d) => d.meta.kind !== "legal"), ...docs.filter((d) => d.meta.kind === "legal")].map(
        (d) => `${site.origin}${d.path}`,
      ),
    );
    for (const m of links) {
      const d = docs.find((x) => `${site.origin}${x.path}` === m[2]);
      expect([m[1], m[3]]).toEqual([d?.meta.title, d?.meta.description]);
    }
    // House copy rules hold here too: US English with no dashes, and nothing from the never-say list.
    expect(llms).not.toMatch(/[–—]/);
    for (const phrase of NEVER_SAY) expect(llms.toLowerCase(), phrase).not.toContain(phrase);
    // A convention file, not a page: no robots or sitemap entry.
    expect(built.get("public/robots.txt")).not.toContain("llms");
    expect(sitemap).not.toContain("llms");
  });

  it("the origin is the Worker's public origin", () => {
    expect(read("wrangler.jsonc")).toContain(`"PUBLIC_ORIGIN": "${site.origin}"`);
  });
});

describe("routes and headers", () => {
  const headers = read("public/_headers");
  const routes = [...headers.matchAll(/^(\/\S*)$/gm)].map((m) => m[1] ?? "");
  const matches = (pattern: string, path: string) =>
    new RegExp(`^${pattern.replace(/[.+?^${}()|[\]\\]/g, "\\$&").replace(/\*/g, ".*")}$`).test(path);

  it("every page route falls under the one /* policy, with no route of its own that could weaken it", () => {
    for (const d of docs) {
      expect(
        routes.filter((r) => matches(r, d.path)),
        d.path,
      ).toEqual(["/*"]);
    }
  });

  it("the CSP lets a JSON-LD block be: it names no inline-script source, and the block is data", () => {
    const csp = headers.split("\n").find((l) => l.includes("Content-Security-Policy:")) ?? "";
    expect(csp).toContain("script-src 'self';");
    expect(csp).not.toContain("unsafe-inline");
  });

  it("every internal link on every page resolves to a page and its anchor, an asset or a redirect", () => {
    const byPath = new Map(pages.map(([rel, html]) => [pathOf(rel), html]));
    const redirects = read("public/_redirects");
    for (const [rel, html] of pages) {
      for (const href of hrefs(html)) {
        if (!href.startsWith("/")) continue;
        const [path = "", frag] = href.split("#");
        const target = byPath.get(path || "/");
        if (target) {
          if (frag) expect(target, `${rel}: ${href}`).toContain(`id="${frag}"`);
        } else {
          const known = existsSync(`${ROOT}public${path}`) || new RegExp(`^${path} `, "m").test(redirects);
          expect(known, `${rel}: ${href}`).toBe(true);
        }
      }
    }
  });
});

describe("the content rules", () => {
  type Doc = Parameters<typeof renderDoc>[0];
  const doc = (body: string, over: Record<string, string | boolean> = {}): Doc => ({
    file: "content/x.md",
    path: "/x",
    out: "public/x.html",
    slug: "x",
    dir: "",
    meta: {
      kind: "legal",
      title: "Test Notice",
      description: "A test notice for the build.",
      numbered: true,
      binds: "this notice",
      effective: "2026-01-02",
      version: "1.0",
      ...over,
    },
    body,
  });
  const render = (body: string, over?: Record<string, string | boolean>) => {
    const d = doc(body, over);
    return renderDoc(d, [d]);
  };

  it("splits frontmatter into flat keys, with booleans, and refuses a file without it", () => {
    expect(splitFrontmatter("---\na: b: c\nn: true\nm: false\n---\nbody\n")).toEqual({
      meta: { a: "b: c", n: true, m: false },
      body: "body\n",
    });
    expect(() => splitFrontmatter("no matter")).toThrow(/missing frontmatter/);
    expect(() => splitFrontmatter("---\nbad line\n---\n")).toThrow(/bad frontmatter line/);
  });

  it("formats dates in US English and refuses an impossible one", () => {
    expect(usDate("2026-11-25")).toBe("November 25, 2026");
    expect(() => usDate("2026-02-30")).toThrow(/bad date/);
  });

  it("fills a slot, indents a block under it, drops an empty one and refuses a missing value", () => {
    expect(fill("<a>\n  {{x}}\n</a>\n{{y}}\n", { x: "1\n2", y: "" })).toBe("<a>\n  1\n  2\n</a>\n");
    expect(fill("<i>{{x}}</i>", { x: "v" })).toBe("<i>v</i>");
    expect(() => fill("{{x}}", {})).toThrow(/no value for \{\{x\}\}/);
  });

  it("numbers clauses and letters list items from the source, and refuses a wrong clause number", () => {
    const html = render("Summary.\n\n## One {#one}\n\n1.1 You must:\n\n1. a\n2. b\n\n1.2 Next.\n");
    expect(html).toContain('<p class="clause" id="1.1"><a class="num" href="#1.1">1.1</a> You must:</p>');
    expect(html).toContain('<li id="1.1b"><a class="num" href="#1.1b">(b)</a> b</li>');
    expect(html).toContain('<h2 id="one-h"><a class="num" href="#one">1</a> One</h2>');
    expect(() => render("Summary.\n\n## One {#one}\n\n1.1 First.\n\n1.3 Third.\n")).toThrow(/should start "1\.2 "/);
    expect(() => render("Summary.\n\n## One {#one}\n\n1. a\n")).toThrow(/needs a clause before it/);
  });

  it("sets an In short line as not binding, and an unnumbered page's paragraphs and steps plain", () => {
    const html = render("Summary.\n\n## One {#one}\n\nIn short: brief.\n\n1.1 Long.\n");
    expect(html).toContain(
      '<p class="short"><span class="sr">Summary, not binding: </span><strong>In short:</strong> brief.</p>',
    );
    const plain = render("Summary.\n\n## One {#one}\n\nText.\n\n1. step\n", { numbered: false });
    expect(plain).toContain("<p>Text.</p>");
    expect(plain).toContain('<ol class="flow">');
    expect(plain).not.toContain('class="num"');
  });

  it("sets the name only where it is the name: not in a host, an address, code, or a heading", () => {
    const html = render(
      "Summary.\n\n## About bloop {#one}\n\n1.1 bloop at bloop.here, hi@bloop.here, `bloop`, and bloop's own.\n",
    );
    expect(html).toContain(
      `<a class="num" href="#1.1">1.1</a> <b class="name">bloop</b> at bloop.here, <a href="mailto:hi@bloop.here">hi@bloop.here</a>, <code>bloop</code>, and <b class="name">bloop</b>'s own.`,
    );
    expect(html).toContain("</a> About bloop</h2>");
  });

  it("turns an ISO date in the text into a time element", () => {
    expect(render("Summary.\n\n## One {#one}\n\n1.1 On 2026-11-25 it began.\n")).toContain(
      'On <time datetime="2026-11-25">November 25, 2026</time> it began.',
    );
  });

  it("draws a table with its caption, a row header, a hidden label in each cell and status chips; a table with no caption is refused", () => {
    const table =
      "| Name | What it does | Status |\n| --- | --- | --- |\n| A | Runs | Live |\n| B | Waits | Planned |\n";
    const html = render(`Summary.\n\n## One {#one}\n\nCaption: What is live\n\n${table}`);
    expect(html).toContain('<caption class="sr">What is live</caption>');
    expect(html).toContain(
      '<tr><th scope="row">A</th><td><span class="label" aria-hidden="true">What it does</span>Runs</td><td><span class="label" aria-hidden="true">Status</span><span class="status on">Live</span></td></tr>',
    );
    expect(html).not.toContain("data-label");
    expect(html).toContain('<span class="status">Planned</span>');
    expect(() => render(`Summary.\n\n## One {#one}\n\n${table}`)).toThrow(/needs a "Caption:" paragraph/);
  });

  it("refuses raw HTML, a heading with no id, and a body that does not open with one summary paragraph", () => {
    expect(() => render("Summary.\n\n## One {#one}\n\n1.1 A <b>tag</b>.\n")).toThrow(/raw HTML/);
    expect(() => render("Summary.\n\n## One\n")).toThrow(/needs \{#id\}/);
    expect(() => render("One.\n\nTwo.\n\n## One {#one}\n")).toThrow(/open with one summary paragraph/);
  });

  it("every content file has the frontmatter its kind needs, and an order", () => {
    for (const d of docs) {
      expect(["legal", "article", "index"], d.file).toContain(d.meta.kind);
      expect(typeof d.meta.title, d.file).toBe("string");
      expect(typeof d.meta.description, d.file).toBe("string");
      if (d.meta.kind === "legal") expect(d.meta.effective, d.file).toMatch(/^\d{4}-\d{2}-\d{2}$/);
      if (d.meta.kind === "article") expect(d.meta.published, d.file).toMatch(/^\d{4}-\d{2}-\d{2}$/);
    }
  });
});

describe("one public address", () => {
  const files = (dir: string): string[] =>
    readdirSync(`${ROOT}${dir}`, { withFileTypes: true }).flatMap((e) =>
      e.isDirectory() ? files(`${dir}/${e.name}`) : [`${dir}/${e.name}`],
    );
  const published = files("public").filter((f) => /\.(html|txt|xml|json)$/.test(f) || f.includes("/.well-known/"));

  it("no page, generated file or .well-known file names any @bloop.here address but the site's one", () => {
    expect(site.email).toBe("hi@bloop.here");
    expect(published).toContain("public/.well-known/security.txt");
    expect(published).toContain("public/llms.txt");
    for (const f of published)
      for (const m of read(f).matchAll(/[\w.+-]+@bloop\.here/g)) expect(m[0], f).toBe(site.email);
  });

  it("content files take the address from site.json through the {{email}} slot, never by hand", () => {
    const sources = files("content").filter((f) => f.endsWith(".md"));
    for (const f of sources) expect(read(f), f).not.toMatch(/@bloop\.here/);
    expect(sources.some((f) => read(f).includes("<{{email}}>"))).toBe(true);
    for (const d of docs) expect(d.body, d.file).not.toContain("{{");
    expect(docs.find((d) => d.path === "/privacy")?.body).toContain(`<${site.email}>`);
  });
});

// Builds the site's generated pages from content/ and keeps one nav, one footer and one head block on every page.
// `node tools/build-pages-cli.mjs` writes; `--check` writes nothing and exits 1 on drift (npm run check:pages). The
// design is in docs/design.md section 6, Site build.
import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Marked } from "marked";

// BUILD_PAGES_ROOT points the build at a copy of the repo; the tests use it to drift a file without touching the real one.
const ROOT = process.env.BUILD_PAGES_ROOT ?? fileURLToPath(new URL("../", import.meta.url));
const WORDS_PER_MINUTE = 220;
const GENERATED = "<!-- GENERATED by tools/build-pages.mjs";

/** @param {string} rel */
const read = (rel) => readFileSync(join(ROOT, rel), "utf8");
/** @param {string} s */
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
// Text from markdown: an entity the author wrote (&nbsp;, &#38;) is kept, as marked's own escape does.
/** @param {string} s */
const escText = (s) =>
  s
    .replace(/&(?!#?\w+;)/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
/** @param {string} s */
const attr = (s) => esc(s).replace(/"/g, "&quot;");

/**
 * @typedef {{ label: string, href: string, in: string[] }} Link
 * @typedef {{ file: string, path?: string, title: string, description?: string, source: string, ld?: string, noindex?: boolean }} HandPage
 * @typedef {{ name: string, origin: string, email: string, waitlist: string, about: string, image: { path: string, width: number, height: number },
 *   links: Link[], robots: { disallow: string[] }, pages: HandPage[] }} Site
 * @typedef {{ file: string, path?: string, title: string, description?: string, source: string, current?: string | undefined,
 *   noindex?: boolean, kind: "site" | "legal" | "article" | "index" | "none", published?: string | undefined,
 *   modified?: string | undefined }} Head
 */

/** @type {Site} */
export const site = JSON.parse(read("content/site.json"));

/** @param {string} iso */
export function usDate(iso) {
  const d = new Date(`${iso}T00:00:00Z`);
  if (Number.isNaN(d.getTime()) || d.toISOString().slice(0, 10) !== iso) throw new Error(`bad date ${iso}`);
  return d.toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric", timeZone: "UTC" });
}
/** @param {string} iso */
const time = (iso) => `<time datetime="${iso}">${usDate(iso)}</time>`;

// "bloop" in running text is the name, set in its own face (design.md section 3); a host, an address or a path is not.
const NAME = /(?<![\w@./-])bloop(?![\w@-]|\.[a-z])/g;
const ISO_DATE = /\b\d{4}-\d{2}-\d{2}\b/g;
/** @param {string} text */
const prose = (text) => escText(text).replace(NAME, '<b class="name">bloop</b>').replace(ISO_DATE, time);

const md = new Marked({
  gfm: true,
  renderer: {
    text(token) {
      return "tokens" in token && token.tokens ? this.parser.parseInline(token.tokens) : prose(token.text);
    },
    /** @returns {string} */
    html() {
      throw new Error("raw HTML in content: the layout owns every tag");
    },
    /** @returns {string} */
    image() {
      throw new Error("images are not supported in content yet");
    },
  },
});
/** @param {string} raw @returns {string} */
const inline = (raw) => /** @type {string} */ (md.parseInline(raw));

/** Fills `{{name}}` slots; a multi-line value keeps the slot's indent, and an empty value drops its line. */
/** @param {string} template @param {Record<string, string>} vars */
export function fill(template, vars) {
  /** @param {string} name */
  const value = (name) => {
    const v = vars[name];
    if (v === undefined) throw new Error(`no value for {{${name}}}`);
    return v;
  };
  return template
    .split("\n")
    .flatMap((line) => {
      const own = /^([ \t]*)\{\{(\w+)\}\}[ \t]*$/.exec(line);
      if (!own) return [line.replace(/\{\{(\w+)\}\}/g, (_m, name) => value(name))];
      const v = value(own[2] ?? "");
      return v === "" ? [] : [indented(v, own[1] ?? "")];
    })
    .join("\n");
}
/** @param {string} text @param {string} indent */
const indented = (text, indent) =>
  text
    .split("\n")
    .map((line) => (line ? indent + line : line))
    .join("\n");


/**
 * @typedef {{ meta: Record<string, string | boolean>, body: string }} Source
 * @typedef {{ file: string, path: string, out: string, slug: string, dir: string, meta: Record<string, string | boolean>, body: string,
 *   mode?: Mode }} Doc
 */

const CODE = /(^```[\s\S]*?^```$|`[^`\n]+`)/gm;
/** `fill` for markdown: a code span or fenced block shows its text as written, so a slot inside it stays literal. */
/** @param {string} md @param {Record<string, string>} vars */
export const fillProse = (md, vars) =>
  md
    .split(CODE)
    .map((part, i) => (i % 2 ? part : fill(part, vars)))
    .join("");

/** @param {string} src @returns {Source} */
export function splitFrontmatter(src) {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(src);
  if (!m) throw new Error("missing frontmatter");
  /** @type {Record<string, string | boolean>} */
  const meta = {};
  for (const line of (m[1] ?? "").split("\n")) {
    const at = line.indexOf(":");
    if (at < 1) throw new Error(`bad frontmatter line: ${line}`);
    const value = line.slice(at + 1).trim();
    meta[line.slice(0, at).trim()] = value === "true" ? true : value === "false" ? false : value;
  }
  return { meta, body: src.slice(m[0].length) };
}

/**
 * @param {string} [base] a content folder under `content/` (`open`) holding drafts at the same relative paths
 * @returns {Doc[]} every content file, in the order of its `order`.
 */
export function loadDocs(base = "") {
  /** @type {Doc[]} */
  const docs = [];
  for (const dir of ["", "articles"]) {
    for (const name of readdirSync(join(ROOT, "content", base, dir)).filter((n) => n.endsWith(".md"))) {
      const file = join("content", base, dir, name);
      const slug = name.slice(0, -3);
      // `{{email}}` and `{{waitlist}}` keep the one public address and the one form URL in site.json, not repeated by hand.
      const { meta, body } = splitFrontmatter(fillProse(read(file), { email: site.email, waitlist: site.waitlist }));
      const path = dir ? (slug === "index" ? `/${dir}` : `/${dir}/${slug}`) : `/${slug}`;
      docs.push({ file, path, out: `public${path}.html`, slug, dir, meta, body });
    }
  }
  return docs.sort(byOrder);
}

/** @param {Doc} a @param {Doc} b */
const byOrder = (a, b) => Number(a.meta.order ?? 0) - Number(b.meta.order ?? 0);

/**
 * The documents a mode serves. Open overlays `content/open/**` on the base documents at the same path (a draft
 * replaces the page, a new path adds one) and writes under `public/open/`, the Worker's variant subtree (ADR 0026).
 * @param {Mode} mode
 */
export function docsFor(mode) {
  const base = loadDocs();
  if (mode === "preview") return base;
  const drafts = loadDocs("open");
  return [...base.filter((d) => !drafts.some((o) => o.path === d.path)), ...drafts]
    .map((d) => ({ ...d, mode, out: `public/open${d.path}.html` }))
    .sort(byOrder);
}

const SECTION_ID = /\s*\{#([\w-]+)\}\s*$/;
const need = (/** @type {Doc} */ doc, /** @type {string} */ key) => {
  const v = doc.meta[key];
  if (typeof v !== "string" || !v) throw new Error(`${doc.file}: frontmatter ${key} is required`);
  return v;
};
// A stacked table's column name over each value (tableHtml); aria-hidden, as readers have the heads.
const LABEL = '<span class="label" aria-hidden="true">';
const label = (/** @type {string} */ head) => `${LABEL}${esc(head)}</span>`;
// The words a reader reads, so not the labels.
const textOf = (/** @type {string} */ html) =>
  html
    .replaceAll(new RegExp(`${LABEL}[^<]*</span>`, "g"), " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/\s+/g, " ")
    .trim();

/** Headings, captions and column heads are set as plain text, so markup in them is an error, not a silent strip. */
/** @param {{ tokens?: import("marked").Token[] }} t @param {string} what @param {string} where */
function plainTokens(t, what, where) {
  if ((t.tokens ?? []).some((x) => x.type !== "text" && x.type !== "escape"))
    throw new Error(`${where}: a ${what} is plain text, with no links, emphasis or code`);
}

/** @param {import("marked").Tokens.Table} t @param {string} caption @param {string} where */
function tableHtml(t, caption, where) {
  for (const c of t.header) plainTokens(c, "column head", where);
  const heads = t.header.map((c) => c.text);
  const cell = (/** @type {string} */ head, /** @type {string} */ raw) =>
    head === "Status" ? `<span class="status${raw === "Live" ? " on" : ""}">${esc(raw)}</span>` : inline(raw);
  // A stacked row (legal.css, under 640) shows each value under its column's name as real text, the label span,
  // rather than `content: attr()`, which can drop the name's spaces.
  const rows = t.rows.map((row) => {
    const cells = row.map((c, i) => {
      const head = heads[i] ?? "";
      if (i === 0) return `<th scope="row">${cell(head, c.text)}</th>`;
      return `<td>${label(head)}${cell(head, c.text)}</td>`;
    });
    return `<tr>${cells.join("")}</tr>`;
  });
  return [
    "<table>",
    `  <caption class="sr">${esc(caption)}</caption>`,
    "  <thead>",
    `    <tr>${heads.map((h) => `<th scope="col">${esc(h)}</th>`).join("")}</tr>`,
    "  </thead>",
    "  <tbody>",
    ...rows.map((r) => `    ${r}`),
    "  </tbody>",
    "</table>",
  ].join("\n");
}

/**
 * One section's blocks. A numbered document (a contract) numbers each paragraph a clause and each list an (a) list under
 * its clause; an unnumbered one (a page of explanation) sets paragraphs plain and ordered lists as steps.
 * @param {import("marked").Token[]} tokens @param {boolean} numbered @param {number} n @param {string} where
 */
function blocksHtml(tokens, numbered, n, where) {
  const out = [];
  let clause = 0;
  let clauseId = "";
  let caption = "";
  for (const t of tokens) {
    if (t.type === "paragraph") {
      const short = numbered && /^In short: /.exec(t.text);
      const cap = /^Caption: /.exec(t.text);
      if (cap) {
        if (caption) throw new Error(`${where}: two "Caption:" paragraphs in a row`);
        plainTokens(t, "caption", where);
        caption = t.text.slice(cap[0].length);
      } else if (short) {
        out.push(
          `<p class="short"><span class="sr">Summary, not binding: </span><strong>In short:</strong> ${inline(t.text.slice(short[0].length))}</p>`,
        );
      } else if (numbered) {
        clause += 1;
        clauseId = `${n}.${clause}`;
        // The source writes each number so a reader of the markdown sees it; the build checks it against the order.
        if (!t.text.startsWith(`${clauseId} `)) throw new Error(`${where}: this clause should start "${clauseId} "`);
        const body = inline(t.text.slice(clauseId.length + 1));
        out.push(`<p class="clause" id="${clauseId}"><a class="num" href="#${clauseId}">${clauseId}</a> ${body}</p>`);
      } else {
        out.push(`<p>${inline(t.text)}</p>`);
      }
    } else if (t.type === "list") {
      const list = /** @type {import("marked").Tokens.List} */ (t);
      if (list.items.some((i) => i.tokens.some((x) => x.type === "list")))
        throw new Error(`${where}: nested lists are not supported`);
      const items = list.items.map((i) => i.text);
      if (!list.ordered) {
        out.push('<ul class="bullets">', ...items.map((i) => `  <li>${inline(i)}</li>`), "</ul>");
      } else if (numbered) {
        if (!clauseId || items.length > 26) throw new Error(`${where}: a lettered list needs a clause before it`);
        out.push(
          '<ol class="items">',
          ...items.map((raw, i) => {
            const id = `${clauseId}${String.fromCharCode(97 + i)}`;
            return `  <li id="${id}"><a class="num" href="#${id}">(${String.fromCharCode(97 + i)})</a> ${inline(raw)}</li>`;
          }),
          "</ol>",
        );
      } else {
        out.push('<ol class="flow">', ...items.map((i) => `  <li>${inline(i)}</li>`), "</ol>");
      }
    } else if (t.type === "table") {
      if (!caption) throw new Error(`${where}: a table needs a "Caption:" paragraph before it`);
      out.push(tableHtml(/** @type {import("marked").Tokens.Table} */ (t), caption, where));
      caption = "";
    } else if (t.type === "heading" && t.depth === 3) {
      plainTokens(t, "heading", where);
      out.push(`<h3>${escText(t.text)}</h3>`);
    } else {
      throw new Error(`${where}: unsupported ${t.type} block`);
    }
  }
  if (caption) throw new Error(`${where}: a "Caption:" paragraph with no table after it`);
  return out.join("\n");
}

/**
 * @typedef {{ id: string, title: string, html: string, versions?: number }} Section
 * @param {Doc} doc @param {import("marked").Token[]} tokens @param {boolean} numbered @returns {{ summary: string, sections: Section[] }}
 */
function parseBody(doc, tokens, numbered) {
  const live = tokens.filter((t) => t.type !== "space");
  const first = live.findIndex((t) => t.type === "heading" && t.depth === 2);
  const intro = live.slice(0, first < 0 ? live.length : first);
  if (intro.length !== 1 || intro[0]?.type !== "paragraph")
    throw new Error(`${doc.file}: open with one summary paragraph`);
  /** @type {{ id: string, title: string, tokens: import("marked").Token[] }[]} */
  const parts = [];
  for (const t of live.slice(intro.length)) {
    if (t.type === "heading" && t.depth === 2) {
      const m = SECTION_ID.exec(t.text);
      if (!m) throw new Error(`${doc.file}: heading "${t.text}" needs {#id}`);
      plainTokens(t, "heading", doc.file);
      parts.push({ id: m[1] ?? "", title: t.text.replace(SECTION_ID, ""), tokens: [] });
    } else {
      parts.at(-1)?.tokens.push(t);
    }
  }
  const sections = parts.map((p, i) => {
    const num = numbered ? `<a class="num" href="#${p.id}">${i + 1}</a> ` : "";
    const html = [
      `<section id="${p.id}" aria-labelledby="${p.id}-h">`,
      `  <h2 id="${p.id}-h">${num}${escText(p.title)}</h2>`,
      indented(blocksHtml(p.tokens, numbered, i + 1, `${doc.file} #${p.id}`), "  "),
      "</section>",
    ].join("\n");
    // A "Version ..." bullet in a bullet list is one entry of a What Changed section.
    const versions = p.tokens
      .filter((t) => t.type === "list" && !(/** @type {import("marked").Tokens.List} */ (t).ordered))
      .flatMap((t) => /** @type {import("marked").Tokens.List} */ (t).items)
      .filter((item) => item.text.startsWith("Version ")).length;
    return { id: p.id, title: p.title, html, versions };
  });
  return { summary: /** @type {import("marked").Tokens.Paragraph} */ (intro[0]).text, sections };
}

/** @param {Doc} doc */
const kindOf = (doc) => /** @type {"legal" | "article" | "index"} */ (need(doc, "kind"));

/** The pages a reader may go to next: the other documents of the same kind, and an article's index. */
/** @param {Doc} doc @param {Doc[]} docs */
function relatedHtml(doc, docs) {
  const kind = kindOf(doc);
  if (kind === "index") return "";
  const links = docs
    .filter((d) => kindOf(d) === kind && d !== doc)
    .map((d) => `<a href="${d.path}">${prose(need(d, "title"))}</a>`);
  if (kind === "article") links.unshift('<a href="/articles">All Articles</a>');
  return `<p class="related">Related: ${links.join(" · ")}</p>`;
}

/** @param {Section[]} sections */
export function readingMinutes(sections) {
  const words = textOf(sections.map((s) => s.html).join(" ")).split(" ").length;
  return Math.max(1, Math.ceil(words / WORDS_PER_MINUTE));
}

/** @param {Doc} doc @param {Doc[]} docs */
export function renderDoc(doc, docs) {
  const kind = kindOf(doc);
  const numbered = doc.meta.numbered === true;
  const title = need(doc, "title");
  const { summary, sections: parsed } = parseBody(doc, md.lexer(doc.body), numbered);
  if (kind === "index" && parsed.length > 0)
    throw new Error(`${doc.file}: an index lists its articles itself; write only the summary paragraph`);
  const sections = kind === "index" ? indexSections(docs) : parsed;

  const summaryNote = doc.meta.summaryNote;
  const summaryHtml =
    typeof summaryNote === "string"
      ? `<div class="summary">\n  <p>${inline(summary)}</p>\n  <p class="small">${esc(summaryNote)}</p>\n</div>`
      : `<p class="summary">${inline(summary)}</p>`;

  const note = numbered
    ? `<p class="note">The 'In short' lines help you read. They are not part of ${need(doc, "binds")}; the full text is what applies.</p>`
    : "";
  const text = [note, ...sections.map((s) => s.html), relatedHtml(doc, docs)].filter(Boolean).join("\n");
  const toc = sections
    .map(
      (s, i) =>
        `<li><a href="#${s.id}">${numbered ? `<span class="num">${i + 1}</span> ` : ""}${esc(s.title)}</a></li>`,
    )
    .join("\n");

  let meta = "";
  let modified;
  if (kind === "legal") {
    const effective = need(doc, "effective");
    modified = effective;
    const changes = sections.find((s) => s.id === "changes");
    const count = changes?.versions ?? 0;
    const versions = `${count > 1 ? "Previous" : "No previous"} versions`;
    meta = `<p class="meta">Effective ${time(effective)} · Version ${need(doc, "version")} · ${changes ? `<a href="#changes">${versions}</a>` : versions}</p>`;
  } else if (kind === "article") {
    const published = need(doc, "published");
    const updated = typeof doc.meta.updated === "string" ? doc.meta.updated : "";
    modified = updated || published;
    const minutes = readingMinutes(sections);
    meta = `<p class="meta">Published ${time(published)}${updated ? ` · Updated ${time(updated)}` : ""} · ${minutes} min read</p>`;
  }

  const head = headOf(doc, modified);
  const html = fill(read("tools/pages/doc.html"), {
    source: doc.file,
    title: esc(title),
    meta,
    panel: doc.meta.panel === true ? read("tools/pages/panel.html").trimEnd() : "",
    summary: summaryHtml,
    toc,
    text,
  });
  const page = injectChrome(html, chromeFor(head), doc.file);
  const ids = [...page.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);
  const dup = ids.find((id, i) => ids.indexOf(id) !== i);
  if (dup) throw new Error(`${doc.file}: id "${dup}" appears twice on the page`);
  return page;
}

/** One section per article, in order: its title, its description and where to read it. */
/** @param {Doc[]} docs @returns {Section[]} */
function indexSections(docs) {
  return docs
    .filter((d) => kindOf(d) === "article")
    .map((d) => {
      const slug = d.slug;
      const minutes = inFile(d, () => readingMinutes(parseBody(d, md.lexer(d.body), false).sections));
      return {
        id: slug,
        title: need(d, "title"),
        html: [
          `<section id="${slug}" aria-labelledby="${slug}-h">`,
          `  <h2 id="${slug}-h">${esc(need(d, "title"))}</h2>`,
          `  <p>${inline(need(d, "description"))}</p>`,
          `  <p><a href="${d.path}">Read the Article</a> · ${minutes} min read</p>`,
          "</section>",
        ].join("\n"),
      };
    });
}

/** @param {Doc} doc @param {string | undefined} modified @returns {Head} */
function headOf(doc, modified) {
  const kind = kindOf(doc);
  const current = kind === "article" || kind === "index" ? "/articles" : doc.path;
  return {
    file: doc.out.replace(/^public\//, ""),
    path: doc.path,
    title: `${site.name}: ${need(doc, "title")}`,
    description: need(doc, "description"),
    source: kind === "legal" ? doc.slug : "articles",
    current,
    kind,
    published: typeof doc.meta.published === "string" ? doc.meta.published : undefined,
    modified,
    mode: doc.mode,
  };
}


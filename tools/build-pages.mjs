const ORG = () => ({ "@type": "Organization", name: site.name, url: `${site.origin}/` });
/** @param {Head} page @returns {object[]} */
function jsonLd(page) {
  const url = `${site.origin}${page.path}`;
  const common = {
    "@context": "https://schema.org",
    name: page.title,
    description: page.description,
    url,
    inLanguage: "en-US",
  };
  if (page.kind === "site") {
    return [
      {
        "@context": "https://schema.org",
        "@graph": [
          {
            "@type": "Organization",
            "@id": `${site.origin}/#organization`,
            name: site.name,
            url: `${site.origin}/`,
            logo: `${site.origin}/apple-touch-icon.png`,
            email: site.email,
          },
          {
            "@type": "WebSite",
            "@id": `${site.origin}/#website`,
            name: site.name,
            url: `${site.origin}/`,
            description: page.description,
            inLanguage: "en-US",
            publisher: { "@id": `${site.origin}/#organization` },
          },
          ...(page.faq
            ? [
                {
                  "@type": "FAQPage",
                  "@id": `${url}#faq`,
                  url,
                  inLanguage: "en-US",
                  mainEntity: page.faq.map(({ q, a }) => ({
                    "@type": "Question",
                    name: q,
                    acceptedAnswer: { "@type": "Answer", text: a },
                  })),
                },
              ]
            : []),
        ],
      },
    ];
  }
  if (page.kind === "article") {
    return [
      {
        "@context": "https://schema.org",
        "@type": "Article",
        headline: page.title.replace(/^bloop: /, ""),
        description: page.description,
        url,
        mainEntityOfPage: url,
        inLanguage: "en-US",
        image: `${site.origin}${site.image.path}`,
        datePublished: page.published,
        dateModified: page.modified ?? page.published,
        author: ORG(),
        publisher: ORG(),
      },
    ];
  }
  if (page.kind === "legal") {
    return [{ ...common, "@type": "WebPage", dateModified: page.modified, publisher: ORG() }];
  }
  if (page.kind === "index") return [{ ...common, "@type": "CollectionPage", publisher: ORG() }];
  return [];
}

/** The head block between the generic tags and the icons: title, description, canonical, previews, structured data. */
/** @param {Head} page */
export function seoHtml(page) {
  const lines = [`<title>${esc(page.title)}</title>`];
  if (page.noindex) lines.push('<meta name="robots" content="noindex">');
  if (page.description && page.path) {
    const url = `${site.origin}${page.path}`;
    const image = `${site.origin}${site.image.path}`;
    const title = attr(page.title);
    const description = attr(page.description);
    lines.push(
      `<meta name="description" content="${description}">`,
      `<link rel="canonical" href="${url}">`,
      `<meta property="og:type" content="${page.kind === "article" ? "article" : "website"}">`,
      `<meta property="og:site_name" content="${site.name}">`,
      `<meta property="og:url" content="${url}">`,
      `<meta property="og:title" content="${title}">`,
      `<meta property="og:description" content="${description}">`,
      `<meta property="og:image" content="${image}">`,
      `<meta property="og:image:width" content="${site.image.width}">`,
      `<meta property="og:image:height" content="${site.image.height}">`,
      `<meta property="og:image:alt" content="bloop: Present Anywhere">`,
      '<meta name="twitter:card" content="summary_large_image">',
      `<meta name="twitter:title" content="${title}">`,
      `<meta name="twitter:description" content="${description}">`,
      `<meta name="twitter:image" content="${image}">`,
    );
    if (page.kind === "article") {
      lines.push(
        `<meta property="article:published_time" content="${page.published}">`,
        `<meta property="article:modified_time" content="${page.modified ?? page.published}">`,
      );
    }
    // A data block, never run, so script-src and Trusted Types do not apply (docs/design.md section 6, Site build).
    for (const block of jsonLd(page)) {
      lines.push(`<script type="application/ld+json">${JSON.stringify(block).replace(/</g, "\\u003c")}</script>`);
    }
  }
  return lines.join("\n");
}


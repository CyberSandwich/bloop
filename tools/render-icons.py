#!/usr/bin/env python3
"""render-icons: public/js/core/icons.js, the glyphs the scripts draw, from Lucide files (docs/design.md section 6),
and public/js/library/glyphs.js, the library page's own set (apart, so the room and phone pages never carry it).

Use: python3 -I tools/render-icons.py ICONS_DIR   (the owner's Lucide set, one <name>.svg per glyph), then
biome format public/js/core/icons.js public/js/library/glyphs.js.
Each glyph's child elements and their attributes are copied as published; the pages' inline SVG carries the same.
"""
import json
import re
import sys
from pathlib import Path
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'public' / 'js' / 'core' / 'icons.js'
# Glyph name used in the code -> Lucide file.
USED = {
    'presentation': 'presentation',
    'file-text': 'file-text',
    'image': 'image',
    'film': 'film',
    'link': 'link',
    'check': 'check',
    'plus': 'plus',
    'arrow-up-right': 'arrow-up-right',
    'chevron-up': 'chevron-up',
}
LIBRARY_OUT = ROOT / 'public' / 'js' / 'library' / 'glyphs.js'
LIBRARY_USED = {
    'file-spreadsheet': 'file-spreadsheet',
    'ellipsis': 'ellipsis',
    'triangle-alert': 'triangle-alert',
    'pencil': 'pencil',
    'download': 'download',
    'trash-2': 'trash-2',
    'arrow-up': 'arrow-up',
    'arrow-down': 'arrow-down',
    'x': 'x',
    'grip-vertical': 'grip-vertical',
    'monitor': 'monitor',
    'rotate-ccw': 'rotate-ccw',
}


def parts(path):
    root = ElementTree.fromstring(path.read_text())
    out = []
    for child in root:
        tag = re.sub(r'^\{.*\}', '', child.tag)
        attrs = dict(child.attrib)
        out.append(attrs['d'] if tag == 'path' and list(attrs) == ['d'] else [tag, attrs])
    return out


def write(icons, out, const, used):
    lines = ['// Generated by tools/render-icons.py (Lucide, ISC); not edited by hand.',
             '/** @import {IconPart} from "../types.js" */',
             f'export const {const} = /** @satisfies {{Record<string, IconPart[]>}} */ ({{']
    for name, file in used.items():
        body = json.dumps(parts(icons / f'{file}.svg'), separators=(', ', ': '))
        lines.append(f'  {json.dumps(name)}: {body},')
    lines.append('});')
    out.write_text('\n'.join(lines) + '\n')


def main():
    icons = Path(sys.argv[1])
    write(icons, OUT, 'ICONS', USED)
    write(icons, LIBRARY_OUT, 'GLYPHS', LIBRARY_USED)


if __name__ == '__main__':
    main()

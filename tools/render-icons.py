#!/usr/bin/env python3
"""render-icons: public/js/core/icons.js, the glyphs the scripts draw, from Lucide files (docs/design.md section 6).

Use: python3 -I tools/render-icons.py ICONS_DIR   (the owner's Lucide set, one <name>.svg per glyph), then
biome format public/js/core/icons.js.
Each glyph's child elements and their attributes are copied as published; the pages' inline SVG carries the same.
"""
import json
import re
import sys
from pathlib import Path
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'public' / 'js' / 'core' / 'icons.js'
# Glyph name used in the code -> Lucide file.
USED = {
    'presentation': 'presentation',
    'file-text': 'file-text',
    'image': 'image',
    'film': 'film',
    'link': 'link',
    'check': 'check',
    'plus': 'plus',
    'arrow-up-right': 'arrow-up-right',
    'chevron-up': 'chevron-up',
}


def parts(path):
    root = ElementTree.fromstring(path.read_text())
    out = []
    for child in root:
        tag = re.sub(r'^\{.*\}', '', child.tag)
        attrs = dict(child.attrib)
        out.append(attrs['d'] if tag == 'path' and list(attrs) == ['d'] else [tag, attrs])
    return out


def main():
    icons = Path(sys.argv[1])
    lines = ['// Generated by tools/render-icons.py (Lucide, ISC); not edited by hand.',
             '/** @import {IconPart} from "../types.js" */',
             'export const ICONS = /** @satisfies {Record<string, IconPart[]>} */ ({']
    for name, file in USED.items():
        body = json.dumps(parts(icons / f'{file}.svg'), separators=(', ', ': '))
        lines.append(f'  {json.dumps(name)}: {body},')
    lines.append('});')
    OUT.write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
